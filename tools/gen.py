"""Generate src/CampfireCards/Generated/*.cs from the design sheets. Run: python -I tools/gen.py (from the project root)."""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DESIGN = os.path.join(ROOT, 'design')
OUT = os.path.join(ROOT, 'src', 'CampfireCards', 'Generated')


def load(name):
    with open(os.path.join(DESIGN, name), encoding='utf-8') as f:
        return json.load(f)


def cs_str(s):
    if s is None:
        return 'null'
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def cs_float(v):
    return repr(float(v)) + 'f' if not isinstance(v, bool) else ('1f' if v else '0f')


def cs_color(a):
    return 'new Color(%sf, %sf, %sf, %sf)' % tuple(a)


HEADER = '// <auto-generated> from design/%s by tools/gen.py. Do not edit; change the sheet. </auto-generated>\n'


def gen_stats(stats, conditions):
    rows = stats['rows']
    lines = [HEADER % 'stats.json and conditions.json', 'namespace CampfireCards.Generated', '{']
    lines.append('    public enum Channel : byte { %s }' % ', '.join(r['id'] for r in rows))
    lines.append('    public enum Condition : byte { %s }' % ', '.join(r['id'] for r in conditions['rows']))
    lines.append('    public enum CapGroup : byte { none, staminaCost, maxStamina }')
    lines.append('    public struct ChannelDef { public Channel Id; public string Label; public bool IsMul; public CapGroup Cap; public bool HigherIsBetter; }')
    lines.append('    public static class ChannelTable')
    lines.append('    {')
    lines.append('        public const int Count = %d;' % len(rows))
    lines.append('        public static readonly ChannelDef[] Defs = new ChannelDef[]')
    lines.append('        {')
    for r in rows:
        lines.append('            new ChannelDef { Id = Channel.%s, Label = %s, IsMul = %s, Cap = CapGroup.%s, HigherIsBetter = %s },' % (
            r['id'], cs_str(r['label']), 'true' if r['op'] == 'mul' else 'false', r['capGroup'], 'true' if r['better'] == 'higher' else 'false'))
    lines.append('        };')
    lines.append('    }')
    lines.append('    public static class ConditionTable')
    lines.append('    {')
    lines.append('        /// <summary>conditions.json meaning, indexed by Condition.</summary>')
    lines.append('        public static readonly string[] Meaning = new string[] { %s };' % ', '.join(cs_str(r['meaning']) for r in conditions['rows']))
    lines.append('    }')
    lines.append('}')
    return '\n'.join(lines) + '\n'


RARITIES = ['common', 'uncommon', 'rare', 'legendary', 'mythic']


def cs_rgba(a):
    return 'new Rgba(%sf, %sf, %sf, %sf)' % tuple(float(x) for x in a)


def gen_cards(cards):
    rows = cards['rows']
    themes = list(cards['themes'].keys())
    art_ids = [r['id'] for r in json.load(open(os.path.join(DESIGN, 'art.json'), encoding='utf-8'))['rows']]
    lines = [HEADER % 'cards.json', 'using System.Collections.Generic;', '', 'namespace CampfireCards.Generated', '{']
    lines.append('    public enum CardRarity : byte { %s }' % ', '.join(r.capitalize() for r in RARITIES))
    lines.append('    public enum ModOp : byte { mul, add, set }')
    lines.append('    public enum ModTarget : byte { self, team, teamAndSelf }')
    lines.append('    public struct Rgba { public float R, G, B, A; public Rgba(float r, float g, float b, float a) { R = r; G = g; B = b; A = a; } }')
    lines.append('    public struct ThemeDef { public string Id; public Rgba Frame; public Rgba Bg; public Rgba Accent; }')
    lines.append('    public struct ModDef { public Channel Channel; public ModOp Op; public float Value; public Condition When; public ModTarget Target; }')
    lines.append('    public sealed class CardDef')
    lines.append('    {')
    lines.append('        public byte Id; public string Key; public string Name; public CardRarity Rarity; public string Category; public string Type;')
    lines.append('        public string Positive; public string Negative; public string Flavor; public bool MultiplayerOnly; public bool DrawsCards;')
    lines.append('        public ModDef[] Mods; public string Ability; public Dictionary<string, float> Params; public int Theme; public int Art;')
    lines.append('        public float Param(string name, float fallback = 0f) { float v; return Params != null && Params.TryGetValue(name, out v) ? v : fallback; }')
    lines.append('    }')
    lines.append('    public static class CardTable')
    lines.append('    {')
    lines.append('        public const int OfferCount = %d;' % cards['offerCount'])
    lines.append('        public static readonly float[] RarityWeights = new float[] { %s };' % ', '.join(cs_float(cards['rarityWeights'][r]) for r in RARITIES))
    lines.append('        public static readonly Rgba[] RarityColors = new Rgba[] { %s };' % ', '.join(cs_rgba(cards['rarityColors'][r]) for r in RARITIES))
    lines.append('        public static readonly string[] SpawnItems = new string[] { %s };' % ', '.join(cs_str(x) for x in cards['spawnItems']))
    lines.append('        public static readonly ThemeDef[] Themes = new ThemeDef[]')
    lines.append('        {')
    for t in themes:
        th = cards['themes'][t]
        lines.append('            new ThemeDef { Id = %s, Frame = %s, Bg = %s, Accent = %s },' % (cs_str(t), cs_rgba(th['frame']), cs_rgba(th['bg']), cs_rgba(th['accent'])))
    lines.append('        };')
    lines.append('        public static readonly CardDef[] Cards = new CardDef[]')
    lines.append('        {')
    for r in rows:
        mods = ', '.join('new ModDef { Channel = Channel.%s, Op = ModOp.%s, Value = %s, When = Condition.%s, Target = ModTarget.%s }' % (
            mo[0], mo[1], cs_float(mo[2]), mo[3], mo[4]) for mo in r['mods'])
        params = ', '.join('{ %s, %s }' % (cs_str(k), cs_float(v)) for k, v in r['params'].items())
        lines.append('            new CardDef { Id = %d, Key = %s, Name = %s, Rarity = CardRarity.%s, Category = %s, Type = %s, Positive = %s, Negative = %s, Flavor = %s, MultiplayerOnly = %s, DrawsCards = %s,' % (
            r['id'], cs_str(r['key']), cs_str(r['name']), r['rarity'].capitalize(), cs_str(r['category']), cs_str(r['type']),
            cs_str(r['positive']), cs_str(r['negative']), cs_str(r['flavor']), 'true' if r['multiplayerOnly'] else 'false', 'true' if r['drawsCards'] else 'false'))
        lines.append('                Mods = new ModDef[] { %s },' % mods)
        lines.append('                Ability = %s, Params = new Dictionary<string, float> { %s }, Theme = %d, Art = %d },' % (
            cs_str(r['ability']), params, themes.index(r['theme']), art_ids.index(r['art'])))
    lines.append('        };')
    lines.append('    }')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def gen_art(art):
    lines = [HEADER % 'art.json', 'namespace CampfireCards.Generated', '{']
    lines.append('    public enum ArtShape { %s }' % ', '.join(art['shapes']))
    lines.append('    public enum ArtColor { %s }' % ', '.join(art['colors']))
    lines.append('    public enum ArtAnim { %s }' % ', '.join(art['anims'].keys()))
    lines.append('    public struct ArtLayer { public ArtShape Shape; public ArtColor Color; public float W, H, X, Y, Rot, Amp, Speed, Phase, Alpha; public ArtAnim Anim; }')
    lines.append('    public struct ArtMotif { public string Id; public ArtLayer[] Layers; }')
    lines.append('    public static class ArtTable')
    lines.append('    {')
    lines.append('        public static readonly ArtMotif[] Motifs = new ArtMotif[]')
    lines.append('        {')
    for r in art['rows']:
        ls = []
        for l in r['layers']:
            ls.append('new ArtLayer { Shape = ArtShape.%s, Color = ArtColor.%s, W = %s, H = %s, X = %s, Y = %s, Rot = %s, Anim = ArtAnim.%s, Amp = %s, Speed = %s, Phase = %s, Alpha = %s }' % (
                l['shape'], l['color'], cs_float(l['size'][0]), cs_float(l['size'][1]), cs_float(l['pos'][0]), cs_float(l['pos'][1]), cs_float(l['rot']),
                l['anim'], cs_float(l['amp']), cs_float(l['speed']), cs_float(l['phase']), cs_float(l['alpha'])))
        lines.append('            new ArtMotif { Id = %s, Layers = new ArtLayer[] {\n                %s } },' % (cs_str(r['id']), ',\n                '.join(ls)))
    lines.append('        };')
    lines.append('    }')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def gen_sounds(snd):
    lines = [HEADER % 'sounds.json', 'namespace CampfireCards.Generated', '{']
    lines.append('    public struct SoundDef { public string Id; public string Kind; public float Duration; public float[] Freqs; public float Volume; }')
    lines.append('    public static class SoundTable')
    lines.append('    {')
    lines.append('        public static readonly SoundDef[] Sounds = new SoundDef[]')
    lines.append('        {')
    for r in snd['rows']:
        lines.append('            new SoundDef { Id = %s, Kind = %s, Duration = %s, Freqs = new float[] { %s }, Volume = %s },' % (
            cs_str(r['id']), cs_str(r['kind']), cs_float(r['duration']), ', '.join(cs_float(f) for f in r['freqs']), cs_float(r['volume'])))
    lines.append('        };')
    lines.append('    }')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def split_params(params):
    """'Campfire __instance, ref float amount' -> [('Campfire __instance', '', '__instance'), ('ref float amount', 'ref ', 'amount')]"""
    out = []
    for p in [x.strip() for x in params.split(',') if x.strip()]:
        toks = p.split()
        mod = ''
        if toks[0] in ('ref', 'out'):
            mod = toks[0] + ' '
        out.append((p, mod, toks[-1]))
    return out


def gen_hooks(hooks):
    lines = [HEADER % 'hooks.json', 'using System;', 'using HarmonyLib;', '', 'namespace CampfireCards.Generated', '{']
    for r in hooks['rows']:
        if r['kind'] != 'harmony':
            continue
        sig = r.get('signature', '').strip()
        if sig:
            types = ', '.join('typeof(%s)' % t.strip() for t in sig.split(','))
            attr = '[HarmonyPatch(typeof(%s), %s, new Type[] { %s })]' % (r['targetType'], cs_str(r['targetMember']), types)
        else:
            attr = '[HarmonyPatch(typeof(%s), %s)]' % (r['targetType'], cs_str(r['targetMember']))
        lines.append('    %s' % attr)
        lines.append('    internal static class Patch_%s' % r['id'])
        lines.append('    {')
        pre = r.get('prefixArgs', '')
        if pre:
            ps = split_params(pre)
            call = ', '.join(m + n for _, m, n in ps)
            if r.get('prefixBool'):
                lines.append('        [HarmonyPrefix] static bool Prefix(%s) { return CampfireCards.Hooks.%sPrefix(%s); }' % (pre, r['handler'], call))
            else:
                lines.append('        [HarmonyPrefix] static void Prefix(%s) { CampfireCards.Hooks.%sPrefix(%s); }' % (pre, r['handler'], call))
        post = r.get('postfixArgs', '')
        if post == '-':
            lines.append('        [HarmonyPostfix] static void Postfix() { CampfireCards.Hooks.%s(); }' % r['handler'])
        elif post:
            ps = split_params(post)
            call = ', '.join(m + n for _, m, n in ps)
            lines.append('        [HarmonyPostfix] static void Postfix(%s) { CampfireCards.Hooks.%s(%s); }' % (post, r['handler'], call))
        lines.append('    }')
        lines.append('')
    lines.append('}')
    return '\n'.join(lines) + '\n'


WRITERS = {
    'byte': ('w.Write({n});', '{n} = r.ReadByte();'),
    'bool': ('w.Write({n});', '{n} = r.ReadBoolean();'),
    'int': ('w.Write({n});', '{n} = r.ReadInt32();'),
    'float': ('w.Write({n});', '{n} = r.ReadSingle();'),
    'double': ('w.Write({n});', '{n} = r.ReadDouble();'),
    'string': ('w.Write({n} ?? "");', '{n} = r.ReadString();'),
    # array lengths come from the network: refuse a length the payload cannot hold before allocating anything
    'byte[]': ('w.Write({n} == null ? 0 : {n}.Length); if ({n} != null) w.Write({n});',
               '{{ int n = r.ReadInt32(); if (n < 0 || n > ms.Length - ms.Position) throw new InvalidDataException("{n}: bad length " + n); {n} = r.ReadBytes(n); }}'),
    'int[]': ('w.Write({n} == null ? 0 : {n}.Length); if ({n} != null) foreach (var x in {n}) w.Write(x);',
              '{{ int n = r.ReadInt32(); if (n < 0 || n > (ms.Length - ms.Position) / 4) throw new InvalidDataException("{n}: bad length " + n); {n} = new int[n]; for (int i = 0; i < n; i++) {n}[i] = r.ReadInt32(); }}'),
}


def gen_net(net):
    lines = [HEADER % 'net.json', 'using System.IO;', '', 'namespace CampfireCards.Net', '{']
    lines.append('    public interface INetEvent { byte EventCode { get; } byte[] Write(); }')
    lines.append('')
    lines.append('    public static class NetCodes')
    lines.append('    {')
    for r in net['rows']:
        lines.append('        public const byte %s = %d;' % (r['name'], r['code']))
    lines.append('        public static readonly byte[] All = new byte[] { %s };' % ', '.join(str(r['code']) for r in net['rows']))
    lines.append('    }')
    lines.append('')
    for r in net['rows']:
        lines.append('    /// <summary>%s. Sender: %s. Receivers: %s.</summary>' % (r['purpose'].replace('\n', ' '), r['sender'], r['receivers']))
        lines.append('    public struct %s : INetEvent' % r['name'])
        lines.append('    {')
        lines.append('        public const byte Code = %d;' % r['code'])
        lines.append('        public byte EventCode => Code;')
        lines.append('        public const bool Reliable = %s;' % ('true' if r['reliable'] else 'false'))
        lines.append('        public const string Receivers = %s;' % cs_str(r['receivers']))
        for f in r['fields']:
            lines.append('        public %s %s;' % (f['type'], f['name']))
        lines.append('        public byte[] Write()')
        lines.append('        {')
        lines.append('            using (var ms = new MemoryStream()) using (var w = new BinaryWriter(ms))')
        lines.append('            {')
        for f in r['fields']:
            lines.append('                ' + WRITERS[f['type']][0].replace('{n}', f['name']))
        lines.append('                w.Flush(); return ms.ToArray();')
        lines.append('            }')
        lines.append('        }')
        lines.append('        public static %s Read(byte[] data)' % r['name'])
        lines.append('        {')
        lines.append('            var v = new %s();' % r['name'])
        lines.append('            using (var ms = new MemoryStream(data)) using (var r = new BinaryReader(ms))')
        lines.append('            {')
        for f in r['fields']:
            lines.append('                ' + WRITERS[f['type']][1].replace('{n}', 'v.' + f['name']))
        lines.append('            }')
        lines.append('            return v;')
        lines.append('        }')
        lines.append('    }')
        lines.append('')
    lines.append('    public static partial class NetDispatcher')
    lines.append('    {')
    lines.append('        /// <summary>Routes a received mod event to its handler. Returns false for codes the mod does not own.</summary>')
    lines.append('        public static bool Dispatch(byte code, byte[] data, int sender)')
    lines.append('        {')
    lines.append('            switch (code)')
    lines.append('            {')
    for r in net['rows']:
        lines.append('                case %d: NetHandlers.%s(%s.Read(data), sender); return true;' % (r['code'], r['handler'], r['name']))
    lines.append('                default: return false;')
    lines.append('            }')
    lines.append('        }')
    lines.append('    }')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def gen_ui(ui):
    lines = [HEADER % 'ui.json', 'using UnityEngine;', '', 'namespace CampfireCards.Generated', '{']
    lines.append('    public static class UiTiming')
    lines.append('    {')
    for k, v in ui['timing'].items():
        lines.append('        public const float %s = %s;' % (k[0].upper() + k[1:], cs_float(v)))
    rr = ui['canvas']['referenceResolution']
    lines.append('        public static readonly Vector2 ReferenceResolution = new Vector2(%sf, %sf);' % (rr[0], rr[1]))
    lines.append('        public const int SortingOrder = %d;' % ui['canvas']['sortingOrder'])
    lines.append('    }')
    lines.append('')
    for r in ui['rows']:
        lines.append('    /// <summary>%s. %s</summary>' % (r['visual'].replace('\n', ' '), r['behaviour'].replace('\n', ' ')))
        lines.append('    public static class Ui_%s' % r['id'])
        lines.append('    {')
        lines.append('        public const string Parent = %s;' % cs_str(r['parent']))
        lines.append('        public static readonly Vector2 Size = new Vector2(%sf, %sf);' % (r['size'][0], r['size'][1]))
        lines.append('        public const string Anchor = %s;' % cs_str(r['anchor']))
        lines.append('        public const string Text = %s;' % cs_str(r['text']))
        lines.append('        public const string SoundOn = %s;' % cs_str(r['soundOn']))
        for k, v in r.get('consts', {}).items():
            if isinstance(v, list) and len(v) == 4:
                lines.append('        public static readonly Color %s = %s;' % (k, cs_color(v)))
            elif isinstance(v, str):
                lines.append('        public const string %s = %s;' % (k, cs_str(v)))
            elif isinstance(v, bool):
                lines.append('        public const bool %s = %s;' % (k, 'true' if v else 'false'))
            else:
                lines.append('        public const float %s = %s;' % (k, cs_float(v)))
        lines.append('    }')
        lines.append('')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def main():
    os.makedirs(OUT, exist_ok=True)
    outputs = {
        'ClimbStats.cs': gen_stats(load('stats.json'), load('conditions.json')),
        'CardTable.cs': gen_cards(load('cards.json')),
        'HarmonyHooks.cs': gen_hooks(load('hooks.json')),
        'NetEvents.cs': gen_net(load('net.json')),
        'UiLayout.cs': gen_ui(load('ui.json')),
        'ArtTable.cs': gen_art(load('art.json')),
        'SoundTable.cs': gen_sounds(load('sounds.json')),
    }
    for name, text in outputs.items():
        path = os.path.join(OUT, name)
        with open(path, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
        print('wrote', os.path.relpath(path, ROOT), len(text.splitlines()), 'lines')


if __name__ == '__main__':
    main()
