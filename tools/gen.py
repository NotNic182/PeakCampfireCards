"""Generate src/PeakRounds/Generated/*.cs from the design sheets. Run: python -I tools/gen.py (from the project root)."""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DESIGN = os.path.join(ROOT, 'design')
OUT = os.path.join(ROOT, 'src', 'PeakRounds', 'Generated')


def load(name):
    with open(os.path.join(DESIGN, name), encoding='utf-8') as f:
        return json.load(f)


def cs_str(s):
    if s is None:
        return 'null'
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def cs_float(v):
    return repr(float(v)) + 'f' if not isinstance(v, bool) else ('1f' if v else '0f')


def cs_color(a):
    return 'new Color(%sf, %sf, %sf, %sf)' % tuple(a)


HEADER = '// <auto-generated> from design/%s by tools/gen.py. Do not edit; change the sheet. </auto-generated>\n'


def gen_stats(stats):
    rows = stats['rows']
    lines = [HEADER % 'stats.json', 'namespace PeakRounds.Generated', '{']
    lines.append('    public enum ClimbStat : byte')
    lines.append('    {')
    for i, r in enumerate(rows):
        lines.append('        %s = %d,' % (r['id'], i))
    lines.append('    }')
    lines.append('')
    lines.append('    public struct ClimbStatDef')
    lines.append('    {')
    lines.append('        public ClimbStat Id; public string Label; public bool IsFlag; public string Unit; public float Min; public float Max;')
    lines.append('        public string Display; public string DisplayNegative; public bool InvertSign; public string AppliesVia;')
    lines.append('    }')
    lines.append('')
    lines.append('    public static class ClimbStatTable')
    lines.append('    {')
    lines.append('        public const int Count = %d;' % len(rows))
    lines.append('        public static readonly ClimbStatDef[] Defs = new ClimbStatDef[]')
    lines.append('        {')
    for r in rows:
        lines.append('            new ClimbStatDef { Id = ClimbStat.%s, Label = %s, IsFlag = %s, Unit = %s, Min = %s, Max = %s, Display = %s, DisplayNegative = %s, InvertSign = %s, AppliesVia = %s },' % (
            r['id'], cs_str(r['label']), 'true' if r['kind'] == 'flag' else 'false', cs_str(r['unit']), cs_float(r['min']), cs_float(r['max']),
            cs_str(r['display']), cs_str(r.get('displayNegative', '')), 'true' if r.get('invertSign') else 'false', cs_str(r['appliesVia'])))
    lines.append('        };')
    lines.append('    }')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def gen_cards(cards):
    rows = cards['rows']
    lines = [HEADER % 'cards.json', 'namespace PeakRounds.Generated', '{']
    lines.append('    public struct EffectDef { public ClimbStat Stat; public float Value; }')
    lines.append('    public struct CardDef { public byte Id; public string Rounds; public bool InDeck; public EffectDef[] Effects; }')
    lines.append('    public static class CardTable')
    lines.append('    {')
    lines.append('        public const int HandSize = %d;' % cards['handSize'])
    rw = cards['rarityWeights']
    lines.append('        public static float RarityWeight(int rarity) { switch (rarity) { case 0: return %s; case 1: return %s; case 2: return %s; default: return 0f; } }' % (cs_float(rw['Common']), cs_float(rw['Uncommon']), cs_float(rw['Rare'])))
    lines.append('        public static readonly CardDef[] Cards = new CardDef[]')
    lines.append('        {')
    for r in rows:
        effs = ', '.join('new EffectDef { Stat = ClimbStat.%s, Value = %s }' % (k, cs_float(v)) for k, v in r['effects'].items())
        lines.append('            new CardDef { Id = %d, Rounds = %s, InDeck = %s, Effects = new EffectDef[] { %s } },' % (r['id'], cs_str(r['rounds']), 'true' if r['inDeck'] else 'false', effs))
    lines.append('        };')
    lines.append('    }')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def split_params(params):
    """'Campfire __instance, ref float amount' -> [('Campfire __instance', '', '__instance'), ('ref float amount', 'ref ', 'amount')]"""
    out = []
    for p in [x.strip() for x in params.split(',') if x.strip()]:
        toks = p.split()
        mod = ''
        if toks[0] in ('ref', 'out'):
            mod = toks[0] + ' '
        out.append((p, mod, toks[-1]))
    return out


def gen_hooks(hooks):
    lines = [HEADER % 'hooks.json', 'using System;', 'using HarmonyLib;', '', 'namespace PeakRounds.Generated', '{']
    for r in hooks['rows']:
        if r['kind'] != 'harmony':
            continue
        sig = r.get('signature', '').strip()
        if sig:
            types = ', '.join('typeof(%s)' % t.strip() for t in sig.split(','))
            attr = '[HarmonyPatch(typeof(%s), %s, new Type[] { %s })]' % (r['targetType'], cs_str(r['targetMember']), types)
        else:
            attr = '[HarmonyPatch(typeof(%s), %s)]' % (r['targetType'], cs_str(r['targetMember']))
        lines.append('    %s' % attr)
        lines.append('    internal static class Patch_%s' % r['id'])
        lines.append('    {')
        pre = r.get('prefixArgs', '')
        if pre:
            ps = split_params(pre)
            call = ', '.join(m + n for _, m, n in ps)
            if r.get('prefixBool'):
                lines.append('        [HarmonyPrefix] static bool Prefix(%s) { return PeakRounds.Hooks.%sPrefix(%s); }' % (pre, r['handler'], call))
            else:
                lines.append('        [HarmonyPrefix] static void Prefix(%s) { PeakRounds.Hooks.%sPrefix(%s); }' % (pre, r['handler'], call))
        post = r.get('postfixArgs', '')
        if post == '-':
            lines.append('        [HarmonyPostfix] static void Postfix() { PeakRounds.Hooks.%s(); }' % r['handler'])
        elif post:
            ps = split_params(post)
            call = ', '.join(m + n for _, m, n in ps)
            lines.append('        [HarmonyPostfix] static void Postfix(%s) { PeakRounds.Hooks.%s(%s); }' % (post, r['handler'], call))
        lines.append('    }')
        lines.append('')
    lines.append('}')
    return '\n'.join(lines) + '\n'


WRITERS = {
    'byte': ('w.Write({n});', '{n} = r.ReadByte();'),
    'bool': ('w.Write({n});', '{n} = r.ReadBoolean();'),
    'int': ('w.Write({n});', '{n} = r.ReadInt32();'),
    'float': ('w.Write({n});', '{n} = r.ReadSingle();'),
    'double': ('w.Write({n});', '{n} = r.ReadDouble();'),
    'string': ('w.Write({n} ?? "");', '{n} = r.ReadString();'),
    'byte[]': ('w.Write({n} == null ? 0 : {n}.Length); if ({n} != null) w.Write({n});', '{{ int n = r.ReadInt32(); {n} = r.ReadBytes(n); }}'),
    'int[]': ('w.Write({n} == null ? 0 : {n}.Length); if ({n} != null) foreach (var x in {n}) w.Write(x);', '{{ int n = r.ReadInt32(); {n} = new int[n]; for (int i = 0; i < n; i++) {n}[i] = r.ReadInt32(); }}'),
}


def gen_net(net):
    lines = [HEADER % 'net.json', 'using System.IO;', '', 'namespace PeakRounds.Net', '{']
    lines.append('    public static class NetCodes')
    lines.append('    {')
    for r in net['rows']:
        lines.append('        public const byte %s = %d;' % (r['name'], r['code']))
    lines.append('        public static readonly byte[] All = new byte[] { %s };' % ', '.join(str(r['code']) for r in net['rows']))
    lines.append('    }')
    lines.append('')
    for r in net['rows']:
        lines.append('    /// <summary>%s. Sender: %s. Receivers: %s.</summary>' % (r['purpose'].replace('\n', ' '), r['sender'], r['receivers']))
        lines.append('    public struct %s' % r['name'])
        lines.append('    {')
        lines.append('        public const byte Code = %d;' % r['code'])
        lines.append('        public const bool Reliable = %s;' % ('true' if r['reliable'] else 'false'))
        lines.append('        public const string Receivers = %s;' % cs_str(r['receivers']))
        for f in r['fields']:
            lines.append('        public %s %s;' % (f['type'], f['name']))
        lines.append('        public byte[] Write()')
        lines.append('        {')
        lines.append('            using (var ms = new MemoryStream()) using (var w = new BinaryWriter(ms))')
        lines.append('            {')
        for f in r['fields']:
            lines.append('                ' + WRITERS[f['type']][0].replace('{n}', f['name']))
        lines.append('                w.Flush(); return ms.ToArray();')
        lines.append('            }')
        lines.append('        }')
        lines.append('        public static %s Read(byte[] data)' % r['name'])
        lines.append('        {')
        lines.append('            var v = new %s();' % r['name'])
        lines.append('            using (var ms = new MemoryStream(data)) using (var r = new BinaryReader(ms))')
        lines.append('            {')
        for f in r['fields']:
            lines.append('                ' + WRITERS[f['type']][1].replace('{n}', 'v.' + f['name']))
        lines.append('            }')
        lines.append('            return v;')
        lines.append('        }')
        lines.append('    }')
        lines.append('')
    lines.append('    public static partial class NetDispatcher')
    lines.append('    {')
    lines.append('        /// <summary>Routes a received mod event to its handler. Returns false for codes the mod does not own.</summary>')
    lines.append('        public static bool Dispatch(byte code, byte[] data, int sender)')
    lines.append('        {')
    lines.append('            switch (code)')
    lines.append('            {')
    for r in net['rows']:
        lines.append('                case %d: NetHandlers.%s(%s.Read(data), sender); return true;' % (r['code'], r['handler'], r['name']))
    lines.append('                default: return false;')
    lines.append('            }')
    lines.append('        }')
    lines.append('    }')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def gen_ui(ui):
    lines = [HEADER % 'ui.json', 'using UnityEngine;', '', 'namespace PeakRounds.Generated', '{']
    lines.append('    public static class UiTiming')
    lines.append('    {')
    for k, v in ui['timing'].items():
        lines.append('        public const float %s = %s;' % (k[0].upper() + k[1:], cs_float(v)))
    rr = ui['canvas']['referenceResolution']
    lines.append('        public static readonly Vector2 ReferenceResolution = new Vector2(%sf, %sf);' % (rr[0], rr[1]))
    lines.append('        public const int SortingOrder = %d;' % ui['canvas']['sortingOrder'])
    lines.append('    }')
    lines.append('')
    for r in ui['rows']:
        lines.append('    /// <summary>%s. %s</summary>' % (r['visual'].replace('\n', ' '), r['behaviour'].replace('\n', ' ')))
        lines.append('    public static class Ui_%s' % r['id'])
        lines.append('    {')
        lines.append('        public const string Parent = %s;' % cs_str(r['parent']))
        lines.append('        public static readonly Vector2 Size = new Vector2(%sf, %sf);' % (r['size'][0], r['size'][1]))
        lines.append('        public const string Anchor = %s;' % cs_str(r['anchor']))
        lines.append('        public const string Text = %s;' % cs_str(r['text']))
        lines.append('        public const string SoundOn = %s;' % cs_str(r['soundOn']))
        for k, v in r.get('consts', {}).items():
            if isinstance(v, list) and len(v) == 4:
                lines.append('        public static readonly Color %s = %s;' % (k, cs_color(v)))
            elif isinstance(v, str):
                lines.append('        public const string %s = %s;' % (k, cs_str(v)))
            elif isinstance(v, bool):
                lines.append('        public const bool %s = %s;' % (k, 'true' if v else 'false'))
            else:
                lines.append('        public const float %s = %s;' % (k, cs_float(v)))
        lines.append('    }')
        lines.append('')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def expand_names(name):
    """'UI_Card_Pick_01..05' -> ['UI_Card_Pick_01', ..., 'UI_Card_Pick_05']; plain identifiers pass through; descriptive text -> []"""
    m = re.match(r'^([A-Za-z0-9_]+?)(\d+)\.\.(\d+)$', name.strip())
    if m:
        base, a, b = m.group(1), m.group(2), m.group(3)
        width = len(a)
        return ['%s%0*d' % (base, width, i) for i in range(int(a), int(b) + 1)]
    if re.match(r'^[A-Za-z0-9_]+$', name.strip()):
        return [name.strip()]
    return []


def gen_rounds_assets(ra):
    lines = [HEADER % 'rounds_assets.json', 'namespace PeakRounds.Generated', '{']
    inst = ra['install']
    lines.append('    public static class RoundsInstall')
    lines.append('    {')
    lines.append('        public const int SteamAppId = %d;' % inst['steamAppId'])
    lines.append('        public const string Exe = %s;' % cs_str(inst['exe']))
    lines.append('        public const string DataFolder = %s;' % cs_str(inst['dataFolder']))
    lines.append('        public const string Managed = %s;' % cs_str(inst['managed']))
    lines.append('        public const string UnityVersion = %s;' % cs_str(inst['unityVersion']))
    lines.append('    }')
    lines.append('')
    for r in ra['rows']:
        names = expand_names(r['name']) if r['kind'] in ('audio', 'texture', 'sprite') else []
        lines.append('    /// <summary>%s — %s. Fallback: %s</summary>' % (r['kind'], r['usedFor'], r['fallback']))
        lines.append('    public static class RA_%s' % r['id'])
        lines.append('    {')
        lines.append('        public const string Kind = %s;' % cs_str(r['kind']))
        lines.append('        public const string File = %s;' % cs_str(r['file']))
        lines.append('        public const string Name = %s;' % cs_str(r['name']))
        lines.append('        public const string Format = %s;' % cs_str(r['format']))
        lines.append('        public const bool Required = %s;' % ('true' if r['required'] else 'false'))
        lines.append('        public static readonly string[] Names = new string[] { %s };' % ', '.join(cs_str(n) for n in names))
        lines.append('    }')
        lines.append('')
    lines.append('    public static class RoundsAudioKeys')
    lines.append('    {')
    for k, v in ra['audioKeys'].items():
        lines.append('        public static readonly string[] %s = RA_%s.Names;' % (k[0].upper() + k[1:], v))
    lines.append('    }')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def main():
    os.makedirs(OUT, exist_ok=True)
    outputs = {
        'ClimbStats.cs': gen_stats(load('stats.json')),
        'CardTable.cs': gen_cards(load('cards.json')),
        'HarmonyHooks.cs': gen_hooks(load('hooks.json')),
        'NetEvents.cs': gen_net(load('net.json')),
        'UiLayout.cs': gen_ui(load('ui.json')),
        'RoundsAssets.cs': gen_rounds_assets(load('rounds_assets.json')),
    }
    for name, text in outputs.items():
        path = os.path.join(OUT, name)
        with open(path, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
        print('wrote', os.path.relpath(path, ROOT), len(text.splitlines()), 'lines')


if __name__ == '__main__':
    main()
